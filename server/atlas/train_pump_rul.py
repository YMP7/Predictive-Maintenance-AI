"""
Train and evaluate the Modbus motor-pump RUL model on SIMULATED run-to-failure data.

The project has no real pump failure data. The runs come from
server/adapters/pump_degradation.py, the same wear model the live ModbusSimulator replays.
The numbers this script writes describe how well the World Model learns that simulator;
they say nothing about real pumps and must be shown with a SIMULATED label.

Protocol (mirrors the C-MAPSS one):
  - train fleet: 100 simulated units, split 80/20 by unit into train and validation
  - checkpoint: the epoch with the lowest validation MSE
  - test fleet: 50 further units from a different seed, each cut at a random cycle;
    one prediction per unit from its last 30-cycle window, against the capped true RUL

Usage:
    python -m server.atlas.train_pump_rul              # train, evaluate, 5-seed spread
    python -m server.atlas.train_pump_rul --quick      # 3 epochs, 1 seed (smoke test)

Writes data/models/modbus_world_model.pt, data/models/modbus_model_metadata.json and
data/pump_rul_evaluation.json.
"""

from __future__ import annotations

import argparse
import json
import logging
import random
import sys
from datetime import datetime, timezone
from pathlib import Path
from typing import Dict, List, Optional, Sequence, Tuple

import numpy as np

ROOT = Path(__file__).resolve().parent.parent.parent
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))

from server.adapters import pump_degradation as pd  # noqa: E402
from server.atlas.world_model import MODELS_DIR, WorldModel, WorldModelConfig  # noqa: E402

logger = logging.getLogger("ATLAS.TrainPumpRUL")

DOMAIN = "modbus"
SEQ_LEN = 30
TRAIN_FLEET_SEED, TEST_FLEET_SEED, TEST_CUT_SEED = 1, 2, 3
N_TRAIN_UNITS, N_TEST_UNITS = 100, 50
SEEDS = [42, 43, 44, 45, 46]
DISCLOSURE = (
    "SIMULATED: trained and evaluated on run-to-failure data generated by "
    "server/adapters/pump_degradation.py. No real pump failure data was used; these numbers "
    "measure fit to the simulator, not performance on real pumps."
)


def phm_score(y_true: np.ndarray, y_pred: np.ndarray) -> float:
    """PHM08 asymmetric score: late predictions cost more than early ones."""
    d = np.asarray(y_pred, dtype=np.float64) - np.asarray(y_true, dtype=np.float64)
    return float(np.sum(np.where(d < 0, np.exp(-d / 13.0) - 1.0, np.exp(d / 10.0) - 1.0)))


def datasets() -> Dict[str, np.ndarray]:
    """Train/validation windows (split by unit) and one terminal window per cut test unit."""
    fleet = pd.simulate_fleet(N_TRAIN_UNITS, TRAIN_FLEET_SEED)
    n_val = N_TRAIN_UNITS // 5
    X_train, y_train = pd.windows(fleet[n_val:], SEQ_LEN)
    X_val, y_val = pd.windows(fleet[:n_val], SEQ_LEN)
    cut_rng = np.random.default_rng(TEST_CUT_SEED)
    X_test, y_test = [], []
    for feats, rul in pd.simulate_fleet(N_TEST_UNITS, TEST_FLEET_SEED):
        end = int(cut_rng.integers(SEQ_LEN, len(feats)))  # last observed cycle, before failure
        X_test.append(feats[end - SEQ_LEN:end])
        y_test.append(rul[end - 1])
    return {"X_train": X_train, "y_train": y_train, "X_val": X_val, "y_val": y_val,
            "X_test": np.asarray(X_test, dtype=np.float32), "y_test": np.asarray(y_test, dtype=np.float32)}


def predict(model: WorldModel, X: np.ndarray) -> np.ndarray:
    import torch

    model.eval()
    with torch.no_grad():
        out = model(torch.tensor(X, dtype=torch.float32)).rul_pred.reshape(-1).numpy()
    return np.clip(out, 0.0, model.config.max_rul)


def metrics(y_true: np.ndarray, y_pred: np.ndarray) -> Dict[str, float]:
    err = y_pred - y_true
    return {"rmse": round(float(np.sqrt(np.mean(err ** 2))), 4), "mae": round(float(np.mean(np.abs(err))), 4),
            "phm_score": round(phm_score(y_true, y_pred), 2), "n_units": int(len(y_true))}


def train_one(data: Dict[str, np.ndarray], seed: int, epochs: int, lr: float = 1e-3,
              batch_size: int = 256) -> Tuple[WorldModel, Dict[str, float], List[float]]:
    """One seeded training run. Returns the best-validation model, its test metrics and the val-loss history."""
    import torch
    import torch.nn as nn
    from torch.utils.data import DataLoader, TensorDataset

    random.seed(seed)
    np.random.seed(seed)
    torch.manual_seed(seed)

    model = WorldModel(WorldModelConfig(feature_dim=len(pd.FEATURES), seq_len=SEQ_LEN, dropout=0.2,
                                        max_rul=pd.MAX_RUL_CAP, domain=DOMAIN))
    opt = torch.optim.Adam(model.parameters(), lr=lr)
    sched = torch.optim.lr_scheduler.ReduceLROnPlateau(opt, mode="min", factor=0.5, patience=5)
    loss_fn = nn.MSELoss()
    loader = DataLoader(TensorDataset(torch.tensor(data["X_train"]), torch.tensor(data["y_train"]).unsqueeze(1)),
                        batch_size=batch_size, shuffle=True, generator=torch.Generator().manual_seed(seed))
    X_val, y_val = torch.tensor(data["X_val"]), torch.tensor(data["y_val"]).unsqueeze(1)

    best, best_state, history = float("inf"), None, []
    for epoch in range(1, epochs + 1):
        model.train()
        for xb, yb in loader:
            opt.zero_grad()
            loss = loss_fn(model(xb).rul_pred, yb)
            loss.backward()
            torch.nn.utils.clip_grad_norm_(model.parameters(), max_norm=1.0)
            opt.step()
        model.eval()
        with torch.no_grad():
            v = float(loss_fn(model(X_val).rul_pred, y_val))
        history.append(round(v, 4))
        sched.step(v)
        if v < best:
            best, best_state = v, {k: t.clone() for k, t in model.state_dict().items()}
        if epoch == 1 or epoch % 10 == 0:
            logger.info(f"seed {seed} epoch {epoch:3d}/{epochs} val MSE {v:.2f}")
    model.load_state_dict(best_state)
    model.eval()
    return model, metrics(data["y_test"], predict(model, data["X_test"])), history


def run(epochs: int = 60, seeds: Optional[Sequence[int]] = None, models_dir: Optional[Path] = None,
        out_path: Optional[Path] = None) -> Dict:
    seeds = list(seeds or SEEDS)
    models_dir = Path(models_dir) if models_dir else MODELS_DIR
    data = datasets()
    logger.info(f"train {len(data['X_train'])} windows, val {len(data['X_val'])}, test {len(data['X_test'])} units")

    runs = []
    saved = None
    for seed in seeds:
        model, m, history = train_one(data, seed, epochs)
        runs.append({"seed": seed, **m})
        if saved is None:  # the first seed is the shipped checkpoint
            saved = (model, m, history)
            models_dir.mkdir(parents=True, exist_ok=True)
            model.save(models_dir / f"{DOMAIN}_world_model.pt")

    model, shipped, history = saved
    # Reference points on the same test units: a constant guess and the cap.
    mean_guess = np.full_like(data["y_test"], float(np.mean(data["y_train"])))
    rmses = [r["rmse"] for r in runs]
    phms = [r["phm_score"] for r in runs]
    result = {
        "domain": DOMAIN,
        "provenance": "SIMULATED",
        "disclosure": DISCLOSURE,
        "generator": "server/adapters/pump_degradation.py",
        "protocol": f"{N_TRAIN_UNITS} simulated training units (80/20 split by unit), {N_TEST_UNITS} held-out simulated "
                    f"units cut at a random cycle, one prediction per unit from the last {SEQ_LEN}-cycle window, "
                    f"truth capped at {int(pd.MAX_RUL_CAP)} cycles",
        "features": list(pd.FEATURES),
        "train_windows": int(len(data["X_train"])),
        "val_windows": int(len(data["X_val"])),
        "epochs": epochs,
        "shipped_checkpoint": {"file": f"{DOMAIN}_world_model.pt", "seed": seeds[0], **shipped},
        "baseline_constant_mean": metrics(data["y_test"], mean_guess),
        "seeds": runs,
        "multi_seed": {"n": len(runs), "rmse_mean": round(float(np.mean(rmses)), 4),
                       "rmse_std": round(float(np.std(rmses)), 4), "phm_mean": round(float(np.mean(phms)), 2),
                       "phm_std": round(float(np.std(phms)), 2)},
        "timestamp": datetime.now(timezone.utc).isoformat().replace("+00:00", "Z"),
    }
    out_path = Path(out_path) if out_path else ROOT / "data" / "pump_rul_evaluation.json"
    out_path.write_text(json.dumps(result, indent=2) + "\n", encoding="utf-8")
    (models_dir / f"{DOMAIN}_model_metadata.json").write_text(json.dumps({
        "domain": DOMAIN, "feature_dim": len(pd.FEATURES), "features": list(pd.FEATURES),
        "provenance": "SIMULATED", "disclosure": DISCLOSURE, "max_rul": pd.MAX_RUL_CAP,
        "train_windows": result["train_windows"], "val_windows": result["val_windows"], "epochs": epochs,
        "seed": seeds[0], "val_loss_history": history, "test": shipped,
    }, indent=2) + "\n", encoding="utf-8")
    return result


def main() -> int:
    logging.basicConfig(level=logging.INFO, format="%(message)s")
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--epochs", type=int, default=60)
    ap.add_argument("--quick", action="store_true", help="3 epochs, 1 seed")
    args = ap.parse_args()
    result = run(epochs=3 if args.quick else args.epochs, seeds=SEEDS[:1] if args.quick else SEEDS)
    print(json.dumps({k: result[k] for k in ("shipped_checkpoint", "baseline_constant_mean", "multi_seed")}, indent=2))
    return 0


if __name__ == "__main__":
    sys.exit(main())
